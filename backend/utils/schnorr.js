const crypto = require('crypto');
const { EDUCATIONAL_PARAMS } = require('../config/constants');

/**
 * Standard positive modulo helper for BigInt
 * @param {bigint} a 
 * @param {bigint} m 
 * @returns {bigint} (a mod m) >= 0
 */
function mod(a, m) {
  const bigA = BigInt(a);
  const bigM = BigInt(m);
  if (bigM <= 0n) throw new Error('Modulus must be positive');
  const res = bigA % bigM;
  return res >= 0n ? res : res + bigM;
}

/**
 * Modular Exponentiation: (base^exponent) mod modulus
 * Implemented using binary exponentiation (Square-and-Multiply)
 * Time Complexity: O(log(exponent))
 * @param {bigint|number|string} base 
 * @param {bigint|number|string} exponent 
 * @param {bigint|number|string} modulus 
 * @returns {bigint}
 */
function modPow(base, exponent, modulus) {
  const modVal = BigInt(modulus);
  if (modVal <= 0n) throw new Error('Modulus must be positive');
  if (modVal === 1n) return 0n;

  let exp = BigInt(exponent);
  if (exp < 0n) throw new Error('Negative exponents not supported in direct modular exponentiation');

  let result = 1n;
  let b = mod(BigInt(base), modVal);

  while (exp > 0n) {
    if (exp & 1n) {
      result = mod(result * b, modVal);
    }
    exp >>= 1n;
    b = mod(b * b, modVal);
  }

  return result;
}

/**
 * Derive private scalar x from user's demo secret (password/passphrase)
 * using SHA-256 and map into the scalar range [1, q - 1].
 * In Schnorr ZKP, x must remain exclusively on the Prover side.
 * @param {string} secret 
 * @param {bigint} q 
 * @returns {{ secret: string, hash: string, hashDecimal: string, scalar: bigint }}
 */
function deriveScalar(secret, q = EDUCATIONAL_PARAMS.q) {
  if (typeof secret !== 'string' || secret.trim().length === 0) {
    throw new Error('Secret must be a non-empty string');
  }

  const hash = crypto.createHash('sha256').update(secret, 'utf8').digest('hex');
  const hashInt = BigInt('0x' + hash);

  // Map into scalar range [1, q - 1]
  // (hashInt % (q - 1)) + 1 guarantees 1 <= x <= q - 1
  const scalar = (hashInt % (q - 1n)) + 1n;

  return {
    secret,
    hash,
    hashDecimal: hashInt.toString(),
    scalar
  };
}

/**
 * Compute Public Key y = g^x mod p
 * @param {bigint} x - Private scalar witness
 * @param {bigint} p - Prime modulus
 * @param {bigint} g - Generator
 * @returns {bigint}
 */
function computePublicKey(x, p = EDUCATIONAL_PARAMS.p, g = EDUCATIONAL_PARAMS.g) {
  const xBig = BigInt(x);
  if (xBig <= 0n) throw new Error('Scalar x must be positive');
  return modPow(BigInt(g), xBig, BigInt(p));
}

/**
 * Generate cryptographically secure random nonce r in range [1, q - 1]
 * Generated locally on the Prover side for commitment.
 * Must NEVER be revealed to the verifier or logged.
 * @param {bigint|number} q 
 * @returns {bigint}
 */
function generateNonce(q = EDUCATIONAL_PARAMS.q) {
  const qBig = BigInt(q);
  const max = Number(qBig - 1n);
  const randomBuf = crypto.randomBytes(4);
  const randomVal = randomBuf.readUInt32BE(0);
  const r = BigInt((randomVal % max) + 1);
  return r;
}

/**
 * Compute commitment t = g^r mod p
 * Generated by Prover and transmitted to Verifier.
 * @param {bigint|number|string} r - Random secret nonce
 * @param {bigint|number|string} p 
 * @param {bigint|number|string} g 
 * @returns {bigint}
 */
function computeCommitment(r, p = EDUCATIONAL_PARAMS.p, g = EDUCATIONAL_PARAMS.g) {
  const rBig = BigInt(r);
  if (rBig <= 0n) throw new Error('Nonce r must be positive');
  return modPow(BigInt(g), rBig, BigInt(p));
}

/**
 * Generate cryptographically secure random challenge e in range [1, q - 1]
 * Generated strictly by the Verifier.
 * @param {bigint|number} q 
 * @returns {bigint}
 */
function generateChallenge(q = EDUCATIONAL_PARAMS.q) {
  const qBig = BigInt(q);
  const max = Number(qBig - 1n);
  const randomBuf = crypto.randomBytes(4);
  const randomVal = randomBuf.readUInt32BE(0);
  const e = BigInt((randomVal % max) + 1);
  return e;
}

/**
 * Compute Prover response z = (r + e * x) mod q
 * Executed on the Prover side upon receiving challenge e.
 * @param {bigint|number|string} r - Secret nonce
 * @param {bigint|number|string} e - Challenge
 * @param {bigint|number|string} x - Secret scalar
 * @param {bigint|number|string} q - Subgroup order
 * @returns {bigint}
 */
function computeResponse(r, e, x, q = EDUCATIONAL_PARAMS.q) {
  return mod(BigInt(r) + BigInt(e) * BigInt(x), BigInt(q));
}

/**
 * Verify Schnorr Proof:
 * Checks whether g^z mod p === (t * (y^e mod p)) mod p
 * 
 * Cryptographic correctness rationale:
 * LHS = g^z mod p = g^(r + e*x) mod p = (g^r * (g^x)^e) mod p = (t * y^e) mod p = RHS
 * 
 * Returns detailed calculation breakdown for academic visualization.
 * @param {bigint|number|string} y - Public key
 * @param {bigint|number|string} t - Commitment
 * @param {bigint|number|string} e - Challenge
 * @param {bigint|number|string} z - Response
 * @param {bigint|number|string} p - Prime modulus
 * @param {bigint|number|string} g - Generator
 * @returns {{
 *   isValid: boolean,
 *   lhs: bigint,
 *   rhs: bigint,
 *   steps: {
 *     gz: bigint,
 *     ye: bigint,
 *     t_ye: bigint
 *   }
 * }}
 */
function verifyProof(y, t, e, z, p = EDUCATIONAL_PARAMS.p, g = EDUCATIONAL_PARAMS.g) {
  const pBig = BigInt(p);
  const gBig = BigInt(g);
  const yBig = BigInt(y);
  const tBig = BigInt(t);
  const eBig = BigInt(e);
  const zBig = BigInt(z);

  // Input domain validation
  if (yBig <= 0n || yBig >= pBig) {
    return {
      isValid: false,
      lhs: 0n,
      rhs: 0n,
      error: `Public key y must be in range [1, p-1] (1 <= y <= ${pBig - 1n})`,
      steps: { gz: 0n, ye: 0n, t_ye: 0n }
    };
  }
  if (tBig <= 0n || tBig >= pBig) {
    return {
      isValid: false,
      lhs: 0n,
      rhs: 0n,
      error: `Commitment t must be in range [1, p-1] (1 <= t <= ${pBig - 1n})`,
      steps: { gz: 0n, ye: 0n, t_ye: 0n }
    };
  }

  // Left-Hand Side: LHS = g^z mod p
  const gz = modPow(gBig, zBig, pBig);
  const lhs = gz;

  // Right-Hand Side: RHS = (t * (y^e mod p)) mod p
  const ye = modPow(yBig, eBig, pBig);
  const rhs = mod(tBig * ye, pBig);

  const isValid = (lhs === rhs);

  return {
    isValid,
    lhs,
    rhs,
    steps: {
      gz,
      ye,
      t_ye: rhs
    }
  };
}

module.exports = {
  mod,
  modPow,
  deriveScalar,
  computePublicKey,
  generateNonce,
  computeCommitment,
  generateChallenge,
  computeResponse,
  verifyProof
};
